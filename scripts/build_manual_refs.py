#!/usr/bin/env python3
"""The user manual's generated pages (DOCS-3): written from the files the app's history lives in.

  build_manual_refs.py           write manual/generated/*.md
  build_manual_refs.py --check   exit 1 when a page would change

  CHANGELOG.md -> generated/history.md (the [docs: ...] pointers and empty sections dropped)

Run it after editing CHANGELOG.md; scripts/check.sh fails while the page is out of date.
"""
import argparse
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "scripts"))
from docs_check import strip_pointers  # noqa: E402

GEN = os.path.join(ROOT, "manual", "generated")
HEADER = "<!-- Generated by scripts/build_manual_refs.py from {src}. Do not edit; edit the source. -->\n\n"


def read(rel):
    with open(os.path.join(ROOT, rel), encoding="utf-8") as f:
        return f.read()


def history_page():
    text = strip_pointers(read("CHANGELOG.md"))
    parts = re.split(r"(?m)^(?=## )", text)[1:]  # the file's title and notes go; the page has its own
    kept = [p.rstrip() for p in parts if p.split("\n", 1)[1:] and p.split("\n", 1)[1].strip()]
    return (HEADER.format(src="CHANGELOG.md") + "# Revision history\n\n"
            "Every release of HelioFITS Peek, newest first, as CHANGELOG.md records it.\n\n"
            + "\n\n".join(kept) + "\n")


PAGES = {"history.md": history_page}


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    bad = []
    for name, make in PAGES.items():
        path = os.path.join(GEN, name)
        new = make()
        old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if old == new:
            continue
        if a.check:
            bad.append(f"manual/generated/{name} is out of date; run scripts/build_manual_refs.py")
        else:
            os.makedirs(GEN, exist_ok=True)
            with open(path, "w", encoding="utf-8") as f:
                f.write(new)
            print(f"wrote manual/generated/{name}")
    for b in bad:
        print(f"manual-refs: FAIL: {b}")
    if not bad:
        print("manual-refs: ok")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
